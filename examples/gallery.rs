//! Renders a small gallery of each supported high-level plot type to
//! SVG, PDF, and PNG, so the output can be visually compared against real
//! R (see the companion `examples/gen_reference.R` script, which
//! produces the equivalent plots with actual R for side-by-side
//! comparison).
//!
//! Run with `cargo run --example gallery`; output lands in
//! `gallery_output/` (relative to the crate root).

use std::fs;

use rs_graphics::backend::pdf::PdfBackend;
use rs_graphics::backend::raster::RasterBackend;
use rs_graphics::backend::svg::SvgBackend;
use rs_graphics::backend::Backend;
use rs_graphics::color::{Color, ColorSpec};
use rs_graphics::device::{
    Device, LegendEntry, LegendKeyword, LegendOptions, LegendPos, LineStyle,
};
use rs_graphics::highlevel::{barplot, barplot_matrix, boxplot, hist, pie, plot};
use rs_graphics::highlevel::{
    BarplotOptions, BoxplotOptions, HistOptions, PieOptions, PlotOptions,
};
use rs_graphics::layout::Layout;
use rs_graphics::lty::LineType;
use rs_graphics::par::{Par, Sides};

/// Parses one of the `examples/data/*.txt` files (one number per line).
///
/// These files are generated by `examples/gen_data.R` and read by *both*
/// this gallery and `examples/gen_reference.R`, so the two produce plots
/// from identical data. They are embedded at compile time so the example
/// doesn't depend on the working directory.
fn parse_data(text: &str) -> Vec<f64> {
    text.lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| l.trim().parse().expect("numeric data file"))
        .collect()
}

/// Lets [`render`] construct any of the three backends generically from
/// just a page size.
trait NewBackend: Backend + Sized {
    fn create(width_in: f64, height_in: f64) -> Self;
}

impl NewBackend for SvgBackend {
    fn create(width_in: f64, height_in: f64) -> Self {
        SvgBackend::new(width_in, height_in)
    }
}

impl NewBackend for PdfBackend {
    fn create(width_in: f64, height_in: f64) -> Self {
        PdfBackend::new(width_in, height_in)
    }
}

impl NewBackend for RasterBackend {
    fn create(width_in: f64, height_in: f64) -> Self {
        RasterBackend::new(width_in, height_in, 150.0, Color::WHITE)
    }
}

fn render<B: NewBackend>(width_in: f64, height_in: f64, draw: fn(&mut Device<B>)) -> B {
    let backend = B::create(width_in, height_in);
    let mut dev = Device::new(backend, Par::default());
    draw(&mut dev);
    dev.into_backend()
}

/// Renders `draw` to all three backends and writes
/// `gallery_output/<name>.{svg,pdf,png}`. `draw` must be a bare `fn`
/// item (not a closure), so it can be instantiated once per backend
/// type via [`render`].
macro_rules! save_gallery_plot {
    ($name:expr, $w:expr, $h:expr, $draw:ident) => {{
        let svg = render::<SvgBackend>($w, $h, $draw);
        fs::write(format!("gallery_output/{}.svg", $name), svg.finish()).expect("write svg");

        let pdf = render::<PdfBackend>($w, $h, $draw);
        fs::write(format!("gallery_output/{}.pdf", $name), pdf.finish()).expect("write pdf");

        let png = render::<RasterBackend>($w, $h, $draw);
        fs::write(format!("gallery_output/{}.png", $name), png.finish()).expect("write png");

        println!("wrote gallery_output/{}.[svg|pdf|png]", $name);
    }};
}

fn draw_scatter<B: Backend>(dev: &mut Device<B>) {
    let x: Vec<f64> = (1..=25).map(|i| i as f64).collect();
    let y = parse_data(include_str!("data/scatter_y.txt"));

    let opts = PlotOptions {
        pch: 19,
        col: ColorSpec::Index(4),
        main: Some("plot(): scatter"),
        xlab: Some("x"),
        ylab: Some("y"),
        ..PlotOptions::default()
    };
    plot(dev, &x, &y, &opts);
}

fn draw_lineplot<B: Backend>(dev: &mut Device<B>) {
    let x: Vec<f64> = (0..=40).map(|i| i as f64 * 0.25).collect();
    let y: Vec<f64> = x.iter().map(|&xi| xi.sin()).collect();

    let opts = PlotOptions {
        type_: rs_graphics::highlevel::PlotType::Lines,
        col: ColorSpec::Index(2),
        lwd: 2.0,
        main: Some("plot(): line"),
        xlab: Some("x"),
        ylab: Some("sin(x)"),
        ..PlotOptions::default()
    };
    plot(dev, &x, &y, &opts);
}

fn draw_legend<B: Backend>(dev: &mut Device<B>) {
    let x: Vec<f64> = (0..=40).map(|i| i as f64 * 0.25).collect();
    let sin: Vec<f64> = x.iter().map(|&v| v.sin()).collect();
    let cos: Vec<f64> = x.iter().map(|&v| v.cos()).collect();

    let opts = PlotOptions {
        type_: rs_graphics::highlevel::PlotType::Lines,
        col: ColorSpec::Index(2),
        lwd: 2.0,
        ylim: Some((-1.0, 1.6)),
        main: Some("legend(\"topright\")"),
        xlab: Some("x"),
        ylab: Some("value"),
        ..PlotOptions::default()
    };
    plot(dev, &x, &sin, &opts);
    dev.lines(
        &x,
        &cos,
        LineStyle::new(ColorSpec::Index(4), 2.0, LineType::from_code(2)),
    );
    let entries = vec![
        LegendEntry::line("sin(x)", ColorSpec::Index(2), 2.0, LineType::from_code(1)),
        LegendEntry::line("cos(x)", ColorSpec::Index(4), 2.0, LineType::from_code(2)),
    ];
    let o = LegendOptions {
        title: Some("Functions".into()),
        ..LegendOptions::default()
    };
    dev.legend_with(LegendPos::Keyword(LegendKeyword::TopRight), &entries, &o);
}

fn draw_hist<B: Backend>(dev: &mut Device<B>) {
    let data = parse_data(include_str!("data/hist_x.txt"));

    let opts = HistOptions {
        main: Some("hist(): approximately normal data"),
        ..HistOptions::default()
    };
    hist(dev, &data, &opts);
}

fn draw_barplot<B: Backend>(dev: &mut Device<B>) {
    let heights = vec![23.0, 41.0, 12.0, 35.0, 28.0];
    let names = vec!["A", "B", "C", "D", "E"]
        .into_iter()
        .map(String::from)
        .collect();

    let opts = BarplotOptions {
        names: Some(names),
        main: Some("barplot()"),
        ylab: Some("value"),
        ..BarplotOptions::default()
    };
    barplot(dev, &heights, &opts);
}

fn barplot_sample_columns() -> Vec<Vec<f64>> {
    vec![
        vec![3.0, 5.0, 2.0],
        vec![4.0, 1.0, 6.0],
        vec![2.0, 2.0, 7.0],
        vec![5.0, 3.0, 1.0],
    ]
}

fn barplot_sample_opts(main: &'static str, beside: bool) -> BarplotOptions<'static> {
    BarplotOptions {
        names: Some(
            vec!["Q1", "Q2", "Q3", "Q4"]
                .into_iter()
                .map(String::from)
                .collect(),
        ),
        legend_text: Some(vec!["x", "y", "z"].into_iter().map(String::from).collect()),
        beside,
        main: Some(main),
        ..BarplotOptions::default()
    }
}

fn draw_barplot_stacked<B: Backend>(dev: &mut Device<B>) {
    let opts = barplot_sample_opts("barplot(): stacked", false);
    barplot_matrix(dev, &barplot_sample_columns(), &opts);
}

fn draw_barplot_beside<B: Backend>(dev: &mut Device<B>) {
    let opts = barplot_sample_opts("barplot(): beside", true);
    barplot_matrix(dev, &barplot_sample_columns(), &opts);
}

fn draw_boxplot<B: Backend>(dev: &mut Device<B>) {
    let groups = vec![
        parse_data(include_str!("data/boxplot_ctrl.txt")),
        parse_data(include_str!("data/boxplot_treatA.txt")),
        parse_data(include_str!("data/boxplot_treatB.txt")),
    ];
    let names = vec!["Ctrl", "Treat A", "Treat B"]
        .into_iter()
        .map(String::from)
        .collect();

    let opts = BoxplotOptions {
        names: Some(names),
        main: Some("boxplot()"),
        ylab: Some("value"),
        ..BoxplotOptions::default()
    };
    boxplot(dev, &groups, &opts);
}

fn draw_pie<B: Backend>(dev: &mut Device<B>) {
    let values = vec![18.0, 25.0, 12.0, 30.0, 15.0];
    let labels = vec!["Alpha", "Beta", "Gamma", "Delta", "Epsilon"]
        .into_iter()
        .map(String::from)
        .collect();

    let opts = PieOptions {
        labels: Some(labels),
        main: Some("pie()"),
        ..PieOptions::default()
    };
    pie(dev, &values, &opts);
}

/// A chart of every plotting symbol: `pch = 0:25` (with `col`, `bg`) plus
/// some character symbols, each labelled underneath.
fn draw_pch<B: Backend>(dev: &mut Device<B>) {
    dev.par.mar = Sides::new(0.5, 0.5, 2.5, 0.5);
    dev.plot_new();
    dev.plot_window((0.5, 7.5), (-0.2, 5.4), false, false);
    let blue = ColorSpec::Color(Color::parse("blue").unwrap());
    let red = ColorSpec::Color(Color::parse("red").unwrap());
    let black = ColorSpec::Color(Color::BLACK);
    for pch in 0..26 {
        let (x, y) = ((pch % 7) as f64 + 1.0, 5.0 - (pch / 7) as f64);
        dev.points(&[x], &[y], pch, blue, red, 2.0);
        dev.text(x, y - 0.45, &pch.to_string(), 0.5, None, 0.0, black, 0.8, 1);
    }
    for (i, ch) in [".", "a", "M", "+", "*", "#", "o"].iter().enumerate() {
        let x = i as f64 + 1.0;
        let pch = ch.chars().next().unwrap() as i32;
        dev.points(&[x], &[0.6], pch, blue, red, 2.0);
        dev.text(x, 0.15, &format!("\"{ch}\""), 0.5, None, 0.0, black, 0.8, 1);
    }
    dev.title(Some("pch: col = \"blue\", bg = \"red\", cex = 2"), None, None, None);
}

/// `layout(matrix(c(1, 1, 2, 3), 2, byrow = TRUE))`: one wide panel above two.
fn draw_multipanel<B: Backend>(dev: &mut Device<B>) {
    dev.layout(Layout::new(&[vec![1, 1], vec![2, 3]]).expect("valid layout"));
    draw_scatter(dev);
    draw_lineplot(dev);
    draw_barplot(dev);
}

fn main() {
    fs::create_dir_all("gallery_output").expect("create gallery_output/");

    save_gallery_plot!("plot_scatter", 6.0, 4.0, draw_scatter);
    save_gallery_plot!("plot_line", 6.0, 4.0, draw_lineplot);
    save_gallery_plot!("legend", 6.0, 4.0, draw_legend);
    save_gallery_plot!("hist", 6.0, 4.0, draw_hist);
    save_gallery_plot!("barplot", 6.0, 4.0, draw_barplot);
    save_gallery_plot!("barplot_stacked", 6.0, 4.0, draw_barplot_stacked);
    save_gallery_plot!("barplot_beside", 6.0, 4.0, draw_barplot_beside);
    save_gallery_plot!("boxplot", 6.0, 4.0, draw_boxplot);
    save_gallery_plot!("pie", 6.0, 6.0, draw_pie);
    save_gallery_plot!("multipanel", 8.0, 6.0, draw_multipanel);
    save_gallery_plot!("pch", 7.0, 6.0, draw_pch);

    println!("\nGallery complete. See gallery_output/ for SVG/PDF/PNG output.");
}
