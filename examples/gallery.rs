//! Renders a small gallery of each supported high-level plot type to
//! SVG, PDF, and PNG, so the output can be visually compared against real
//! R (see the companion `examples/gen_reference.R` script, which
//! produces the equivalent plots with actual R for side-by-side
//! comparison).
//!
//! Run with `cargo run --example gallery`; output lands in
//! `gallery_output/` (relative to the crate root).

use rs_graphics::prelude::*;

/// Parses one of the `examples/data/*.txt` files (one number per line).
///
/// These files are generated by `examples/gen_data.R` and read by *both*
/// this gallery and `examples/gen_reference.R`, so the two produce plots
/// from identical data. They are embedded at compile time so the example
/// doesn't depend on the working directory.
fn parse_data(text: &str) -> Vec<f64> {
    text.lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| l.trim().parse().expect("numeric data file"))
        .collect()
}

/// Renders `draw` to `gallery_output/<name>.{svg,pdf,png}`.
fn save_gallery_plot(name: &str, width_in: f64, height_in: f64, draw: fn(&mut Device<AnyBackend>)) {
    for format in ["svg", "pdf", "png"] {
        let mut dev = Device::format(format, format!("gallery_output/{name}.{format}"))
            .width(width_in)
            .height(height_in)
            .res(300.0)
            .open()
            .expect("open gallery file");
        draw(&mut dev);
        dev.close().expect("write gallery file");
    }
    println!("wrote gallery_output/{name}.[svg|pdf|png]");
}

fn draw_scatter<B: Backend>(dev: &mut Device<B>) {
    let x: Vec<f64> = (1..=25).map(|i| i as f64).collect();
    let y = parse_data(include_str!("data/scatter_y.txt"));

    let opts = PlotOptions::default()
        .pch(19)
        .col(4)
        .main("plot(): scatter")
        .xlab("x")
        .ylab("y");
    dev.plot(&x, &y).with(&opts).draw();
}

fn draw_lineplot<B: Backend>(dev: &mut Device<B>) {
    let x: Vec<f64> = (0..=40).map(|i| i as f64 * 0.25).collect();
    let y: Vec<f64> = x.iter().map(|&xi| xi.sin()).collect();

    let opts = PlotOptions::default()
        .type_(PlotType::Lines)
        .col(2)
        .lwd(2.0)
        .main("plot(): line")
        .xlab("x")
        .ylab("sin(x)");
    dev.plot(&x, &y).with(&opts).draw();
}

fn draw_log<B: Backend>(dev: &mut Device<B>) {
    let x: Vec<f64> = (0..=15).map(|i| 10f64.powf(i as f64 / 5.0)).collect();
    let y: Vec<f64> = x.iter().map(|&v| 2.0 * v.powf(1.5)).collect();

    let opts = PlotOptions::default()
        .type_(PlotType::Both)
        .pch(19)
        .col(4)
        .xlog(true)
        .ylog(true)
        .main("plot(): log = \"xy\"")
        .xlab("x")
        .ylab("2 * x^1.5");
    dev.plot(&x, &y).with(&opts).draw();
}

fn draw_types_h_s<B: Backend>(dev: &mut Device<B>) {
    dev.par().mfrow(1, 2).draw();

    // type = "h": counts as vertical lines.
    let k: Vec<f64> = (0..=8).map(f64::from).collect();
    let counts = [2.0, 5.0, 9.0, 14.0, 11.0, 7.0, 4.0, 2.0, 1.0];
    dev.plot(&k, &counts)
        .type_(PlotType::Histogram)
        .lwd(4.0)
        .col(4)
        .main("plot(): type = \"h\"")
        .xlab("k")
        .ylab("count")
        .draw();

    // type = "s": an empirical CDF as stair steps.
    let mut x = parse_data(include_str!("data/hist_x.txt"));
    x.sort_by(f64::total_cmp);
    let n = x.len() as f64;
    let fx: Vec<f64> = (1..=x.len()).map(|i| i as f64 / n).collect();
    dev.plot(&x, &fx)
        .type_(PlotType::Steps)
        .main("plot(): type = \"s\"")
        .xlab("x")
        .ylab("Fn(x)")
        .draw();
}

fn draw_abline_log<B: Backend>(dev: &mut Device<B>) {
    let x: Vec<f64> = (0..=15).map(|i| 10f64.powf(i as f64 / 5.0)).collect();
    let y: Vec<f64> = x
        .iter()
        .enumerate()
        .map(|(i, &v)| 2.0 * v.powf(1.5) * 10f64.powf(0.15 * (3.0 * i as f64).sin()))
        .collect();

    let opts = PlotOptions::default()
        .pch(19)
        .xlog(true)
        .ylog(true)
        .main("abline() on log axes")
        .xlab("x")
        .ylab("y");
    dev.plot(&x, &y).with(&opts).draw();
    let grey = ColorSpec::from("grey");
    dev.abline()
        .h(1000.0)
        .v(10.0)
        .col(grey)
        .lty("dashed")
        .draw();
    dev.abline().a(2f64.log10()).b(1.5).col(2).lwd(2.0).draw();
    dev.abline().a(2000).b(20).untf(true).col(3).lwd(2.0).draw();
    let entries = vec![
        LegendEntry::line("abline(log10(2), 1.5)", 2, 2.0, "solid"),
        LegendEntry::line("abline(2000, 20, untf = TRUE)", 3, 2.0, "solid"),
        LegendEntry::line("abline(h = 1000, v = 10)", grey, 1.0, "dashed"),
    ];
    let o = LegendOptions::default().bg(Color::WHITE);
    dev.legend("topleft", &entries).with(&o).draw();
}

fn draw_legend<B: Backend>(dev: &mut Device<B>) {
    let x: Vec<f64> = (0..=40).map(|i| i as f64 * 0.25).collect();
    let sin: Vec<f64> = x.iter().map(|&v| v.sin()).collect();
    let cos: Vec<f64> = x.iter().map(|&v| v.cos()).collect();

    let opts = PlotOptions::default()
        .type_(PlotType::Lines)
        .col(2)
        .lwd(2.0)
        .ylim(-1.0, 1.6)
        .main("legend(\"topright\")")
        .xlab("x")
        .ylab("value");
    dev.plot(&x, &sin).with(&opts).draw();
    let cos_line = XyOptions::default().col(4).lwd(2.0).lty("dashed");
    dev.lines(&x, &cos).with(&cos_line).draw();
    let entries = vec![
        LegendEntry::line("sin(x)", 2, 2.0, "solid"),
        LegendEntry::line("cos(x)", 4, 2.0, "dashed"),
    ];
    let o = LegendOptions::default().title("Functions");
    dev.legend("topright", &entries).with(&o).draw();
}

fn draw_hist<B: Backend>(dev: &mut Device<B>) {
    let data = parse_data(include_str!("data/hist_x.txt"));
    let opts = HistOptions::default().main("hist(): approximately normal data");
    dev.hist(&data).with(&opts).draw();
}

fn draw_barplot<B: Backend>(dev: &mut Device<B>) {
    let heights = vec![23.0, 41.0, 12.0, 35.0, 28.0];
    let opts = BarplotOptions::default()
        .names(["A", "B", "C", "D", "E"])
        .main("barplot()")
        .ylab("value");
    dev.barplot(&heights).with(&opts).draw();
}

fn barplot_sample_columns() -> Vec<Vec<f64>> {
    vec![
        vec![3.0, 5.0, 2.0],
        vec![4.0, 1.0, 6.0],
        vec![2.0, 2.0, 7.0],
        vec![5.0, 3.0, 1.0],
    ]
}

fn barplot_sample_opts(main: &'static str, beside: bool) -> BarplotOptions {
    BarplotOptions::default()
        .names(["Q1", "Q2", "Q3", "Q4"])
        .legend_text(["x", "y", "z"])
        .beside(beside)
        .main(main)
}

fn draw_barplot_stacked<B: Backend>(dev: &mut Device<B>) {
    let opts = barplot_sample_opts("barplot(): stacked", false);
    dev.barplot(barplot_sample_columns()).with(&opts).draw();
}

fn draw_barplot_beside<B: Backend>(dev: &mut Device<B>) {
    let opts = barplot_sample_opts("barplot(): beside", true);
    dev.barplot(barplot_sample_columns()).with(&opts).draw();
}

fn boxplot_sample_groups() -> Vec<Vec<f64>> {
    vec![
        parse_data(include_str!("data/boxplot_ctrl.txt")),
        parse_data(include_str!("data/boxplot_treatA.txt")),
        parse_data(include_str!("data/boxplot_treatB.txt")),
    ]
}

fn draw_boxplot<B: Backend>(dev: &mut Device<B>) {
    let opts = BoxplotOptions::default()
        .names(["Ctrl", "Treat A", "Treat B"])
        .main("boxplot()")
        .ylab("value");
    dev.boxplot(&boxplot_sample_groups()).with(&opts).draw();
}

fn draw_boxplot_horizontal<B: Backend>(dev: &mut Device<B>) {
    let opts = BoxplotOptions::default()
        .names(["Ctrl", "Treat A", "Treat B"])
        .horizontal(true)
        .main("boxplot(horizontal = TRUE)")
        .xlab("value");
    dev.boxplot(&boxplot_sample_groups()).with(&opts).draw();
}

fn draw_pie<B: Backend>(dev: &mut Device<B>) {
    let values = vec![18.0, 25.0, 12.0, 30.0, 15.0];
    let opts = PieOptions::default()
        .labels(["Alpha", "Beta", "Gamma", "Delta", "Epsilon"])
        .main("pie()");
    dev.pie(&values).with(&opts).draw();
}

/// A chart of every plotting symbol: `pch = 0:25` (with `col`, `bg`) plus
/// some character symbols, each labelled underneath.
fn draw_pch<B: Backend>(dev: &mut Device<B>) {
    dev.par.mar = Sides::new(0.5, 0.5, 2.5, 0.5);
    dev.plot_new();
    dev.plot_window((0.5, 7.5), (-0.2, 5.4)).draw();
    let symbol = |pch: i32| XyOptions::default().pch(pch).col("blue").bg("red").cex(2.0);
    let label = TextOptions::default().col(Color::BLACK).cex(0.8);
    for pch in 0..26 {
        let (x, y) = ((pch % 7) as f64 + 1.0, 5.0 - (pch / 7) as f64);
        dev.points(&[x], &[y]).with(&symbol(pch)).draw();
        dev.text(&[x], &[y - 0.45], &[pch.to_string()])
            .with(&label)
            .draw();
    }
    for (i, ch) in ['.', 'a', 'M', '+', '*', '#', 'o'].into_iter().enumerate() {
        let x = i as f64 + 1.0;
        dev.points(&[x], &[0.6]).with(&symbol(ch as i32)).draw();
        dev.text(&[x], &[0.15], &[format!("\"{ch}\"")])
            .with(&label)
            .draw();
    }
    dev.title()
        .main("pch: col = \"blue\", bg = \"red\", cex = 2")
        .draw();
}

/// `layout(matrix(c(1, 1, 2, 3), 2, byrow = TRUE))`: one wide panel above two.
fn draw_multipanel<B: Backend>(dev: &mut Device<B>) {
    dev.layout(Layout::new(&[vec![1, 1], vec![2, 3]]).expect("valid layout"));
    draw_scatter(dev);
    draw_lineplot(dev);
    draw_barplot(dev);
}

/// Three pages in one PDF: each `plot_new()` on a one-figure page starts
/// a new page, as with R's `pdf()`. (SVG and PNG hold one page.)
fn draw_multipage<B: Backend>(dev: &mut Device<B>) {
    draw_scatter(dev);
    draw_hist(dev);
    draw_boxplot(dev);
}

fn main() {
    std::fs::create_dir_all("gallery_output").expect("create gallery_output/");

    save_gallery_plot("plot_scatter", 6.0, 4.0, draw_scatter);
    save_gallery_plot("plot_line", 6.0, 4.0, draw_lineplot);
    save_gallery_plot("plot_log", 6.0, 4.0, draw_log);
    save_gallery_plot("plot_h_s", 8.0, 4.0, draw_types_h_s);
    save_gallery_plot("abline_log", 6.0, 4.0, draw_abline_log);
    save_gallery_plot("legend", 6.0, 4.0, draw_legend);
    save_gallery_plot("hist", 6.0, 4.0, draw_hist);
    save_gallery_plot("barplot", 6.0, 4.0, draw_barplot);
    save_gallery_plot("barplot_stacked", 6.0, 4.0, draw_barplot_stacked);
    save_gallery_plot("barplot_beside", 6.0, 4.0, draw_barplot_beside);
    save_gallery_plot("boxplot", 6.0, 4.0, draw_boxplot);
    save_gallery_plot("boxplot_horizontal", 6.0, 4.0, draw_boxplot_horizontal);
    save_gallery_plot("pie", 6.0, 6.0, draw_pie);
    save_gallery_plot("multipanel", 8.0, 6.0, draw_multipanel);
    save_gallery_plot("pch", 7.0, 6.0, draw_pch);

    let mut dev = Device::pdf("gallery_output/multipage.pdf")
        .width(6.0)
        .height(4.0)
        .open()
        .expect("open gallery file");
    draw_multipage(&mut dev);
    dev.close().expect("write pdf");
    println!("wrote gallery_output/multipage.pdf (3 pages)");

    println!("\nGallery complete. See gallery_output/ for SVG/PDF/PNG output.");
}
